def test_update_smtp_credentials(user, store, server_settings, trust_test_cert):
    client, _ = user
    store.add_account("frank@sender.test", PASSWORD)
    inbox_id = client.post("/api/v1/inboxes/smtp", json=_connect_body(server_settings, "frank@sender.test")).json()["id"]

    # Switch to the STARTTLS servers, keeping the saved password
    new_settings = {**server_settings("starttls", "starttls"), "username": "frank@sender.test", "password": ""}
    updated = client.put(f"/api/v1/inboxes/{inbox_id}/smtp", json=new_settings)
    assert updated.status_code == 200, updated.text
    assert updated.json()["smtp"]["smtp_security"] == "starttls"

    # A new password that doesn't work is rejected and nothing changes
    rejected = client.put(f"/api/v1/inboxes/{inbox_id}/smtp", json={**new_settings, "password": "wrong"})
    assert rejected.status_code == 400 and rejected.json()["detail"]["reason"] == "auth"

    # The password changed at the provider - update it
    store.accounts["frank@sender.test"].password = "new password"
    assert client.post(f"/api/v1/inboxes/{inbox_id}/test").json()["success"] is False
    assert client.put(f"/api/v1/inboxes/{inbox_id}/smtp", json={**new_settings, "password": "new password"}).status_code == 200
    assert client.post(f"/api/v1/inboxes/{inbox_id}/test").json()["success"] is True


