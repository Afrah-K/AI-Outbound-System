def test_password_encryption_roundtrip_and_errors(monkeypatch):
    token = encrypt_password("s3cret")
    assert "s3cret" not in token and decrypt_password(token) == "s3cret"

    monkeypatch.setattr(settings, "mail_credentials_key", Fernet.generate_key().decode())
    with pytest.raises(MailCredentialsError, match="changed since it was saved"):
        decrypt_password(token)

    monkeypatch.setattr(settings, "mail_credentials_key", None)
    with pytest.raises(MailCredentialsError, match="MAIL_CREDENTIALS_KEY is not set"):
        encrypt_password("x")

    monkeypatch.setattr(settings, "mail_credentials_key", "too-short")
    with pytest.raises(MailCredentialsError, match="at least 32 characters"):
        encrypt_password("x")

    # Any long random secret works (e.g. one generated by the hosting platform)
    monkeypatch.setattr(settings, "mail_credentials_key", "x" * 40)
    assert decrypt_password(encrypt_password("pw")) == "pw"


def test_provider_for_picks_the_provider(monkeypatch, server_settings):
    from app.integrations.gmail import service as gmail_service
    from app.models import Inbox

    created = []

    class FakeGmail:
        def __init__(self, access_token, refresh_token, token_expiry):
            created.append((access_token, refresh_token, token_expiry))
            self.updated_tokens = {"access_token": "refreshed", "token_expiry": datetime(2030, 1, 1)}

    monkeypatch.setattr(gmail_service, "GmailService", FakeGmail)

    gmail_inbox = Inbox(email_address="g@gmail.test", access_token="a", refresh_token="r")
    assert gmail_inbox.provider is None or gmail_inbox.provider == "gmail"
    gmail = provider_for(gmail_inbox)
    assert isinstance(gmail, FakeGmail) and created == [("a", "r", None)]
    assert sync_tokens(gmail_inbox, gmail) is True and gmail_inbox.access_token == "refreshed"

    smtp_inbox = Inbox(email_address=ALICE, provider="smtp", username=ALICE,
                       password_encrypted=encrypt_password(PASSWORD), **server_settings())
    smtp = provider_for(smtp_inbox)
    assert isinstance(smtp, SmtpImapService) and smtp.updated_tokens == {}
    assert sync_tokens(smtp_inbox, smtp) is False


