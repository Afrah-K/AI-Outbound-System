def test_existing_inboxes_become_gmail_on_upgrade(tmp_path, monkeypatch):
    """The startup schema upgrade adds the new columns; rows from before get provider='gmail'."""
    import app.database as database
    from app.models.base import Base

    engine = create_engine(f"sqlite:///{tmp_path / 'old.db'}")
    with engine.begin() as conn:
        conn.execute(text(
            "CREATE TABLE inboxes (id INTEGER PRIMARY KEY, owner_id INTEGER, email_address VARCHAR(255), "
            "domain VARCHAR(255), access_token TEXT, refresh_token VARCHAR(512))"
        ))
        conn.execute(text("INSERT INTO inboxes (email_address, domain, access_token, refresh_token) VALUES ('old@gmail.test', 'gmail.test', 'a', 'r')"))
    monkeypatch.setattr(database, "engine", engine)
    database._add_missing_columns(Base.metadata)

    with engine.connect() as conn:
        row = conn.execute(text("SELECT provider, smtp_host, password_encrypted FROM inboxes")).one()
    assert tuple(row) == ("gmail", None, None)


