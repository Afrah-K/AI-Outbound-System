def test_warmup_and_placement_between_smtp_inboxes(owner_db, store, server_settings, trust_test_cert):
    from app.models import PlacementCheck, WarmupLog
    from app.services.placement import resolve_pending
    from app.services.warmup import _send_and_log

    store.add_account("ivy@sender.test", PASSWORD)
    store.add_account("jack@other.test", PASSWORD)
    sender = _smtp_inbox(owner_db, "ivy@sender.test", server_settings)
    recipient = _smtp_inbox(owner_db, "jack@other.test", server_settings)

    assert asyncio.run(_send_and_log(owner_db, sender, recipient)) is True
    assert sender.emails_sent_today == 1 and sender.warmup_emails_sent == 1   # same counters as Gmail inboxes
    assert recipient.emails_sent_today == 1                                     # the warm-up reply
    assert {w.action for w in owner_db.query(WarmupLog)} == {"sent", "received", "replied"}

    checks = owner_db.query(PlacementCheck).all()
    assert len(checks) == 2  # the warm-up email and its reply
    for check in checks:
        check.sent_at = datetime.utcnow() - timedelta(minutes=2)  # past the delivery delay
    owner_db.commit()

    store.junk_rule = lambda raw: False
    summary = asyncio.run(resolve_pending(owner_db))
    assert summary == {"checked": 2, "resolved": 2}
    assert {c.placement for c in owner_db.query(PlacementCheck)} == {"inbox"}
